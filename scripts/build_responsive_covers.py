#!/usr/bin/env python3
"""Build non-destructive responsive WebP copies of curated byLYNCH covers.

Original photographs are untouched. Metadata provides accurate actual image
widths to Jekyll's picture-element fallback.
"""
from pathlib import Path

from PIL import Image, ImageOps
import yaml

ROOT = Path(__file__).resolve().parent.parent
ORIGINALS = ROOT / "assets" / "uploads"
TARGET = ROOT / "assets" / "optimized" / "covers"
MANIFEST = ROOT / "_data" / "responsive_covers.yml"
WIDTHS = (480, 960)
QUALITY = 82


def generate() -> None:
    featured = yaml.safe_load((ROOT / "_data" / "featured.yml").read_text(encoding="utf-8"))
    if not isinstance(featured, dict) or len(featured) != 52:
        raise RuntimeError("Expected 52 curated featured cover mappings")

    entries = {}
    original_sum = 0
    converted_sum = 0

    for slug, rel_path in sorted(featured.items()):
        rel = Path(str(rel_path))
        if rel.is_absolute() or ".." in rel.parts or rel.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
            raise ValueError(f"Unsafe original path: {slug} = {rel_path}")
        original = ORIGINALS / rel
        if not original.is_file():
            raise FileNotFoundError(original)
        original_sum += original.stat().st_size

        with Image.open(original) as source:
            photo = ImageOps.exif_transpose(source)
            width, height = photo.size
            icc = source.info.get("icc_profile")
            if photo.mode not in ("RGB", "RGBA"):
                photo = photo.convert("RGBA" if "A" in photo.getbands() else "RGB")

            records = []
            for target_width in sorted({min(width, w) for w in WIDTHS}):
                target_height = max(1, round(height * (target_width / width)))
                output = photo if target_width == width else photo.resize(
                    (target_width, target_height), Image.Resampling.LANCZOS
                )
                dst_rel = rel.with_name(f"{rel.stem}-{target_width}.webp")
                dst = TARGET / dst_rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                kwargs = {"format": "WEBP", "quality": QUALITY, "method": 6}
                if icc:
                    kwargs["icc_profile"] = icc
                output.save(dst, **kwargs)
                converted_sum += dst.stat().st_size
                records.append({"path": dst_rel.as_posix(), "width": target_width})

        entry = {
            "original_width": width,
            "original_height": height,
            "small": records[0]["path"],
            "small_width": records[0]["width"],
        }
        if len(records) > 1:
            entry["large"] = records[1]["path"]
            entry["large_width"] = records[1]["width"]
        entries[slug] = entry

    MANIFEST.write_text(
        "# GENERATED BY scripts/build_responsive_covers.py — DO NOT HAND EDIT\n"
        + yaml.safe_dump(entries, sort_keys=True, allow_unicode=True),
        encoding="utf-8",
    )
    variants = sum(1 + ("large" in entry) for entry in entries.values())
    print(
        f"{variants} optimized files for {len(entries)} covers. "
        f"Original cover files: {original_sum / 1e6:.2f} MB; "
        f"derivatives combined: {converted_sum / 1e6:.2f} MB."
    )


if __name__ == "__main__":
    generate()
